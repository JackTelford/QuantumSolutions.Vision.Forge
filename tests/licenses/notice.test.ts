import assert from 'node:assert/strict';
import { dirname, resolve } from 'node:path';
import { describe, it } from 'node:test';
import { fileURLToPath } from 'node:url';
import { checkLicenses } from '../../src/licenses/check.ts';
import { readInstalledPackages } from '../../src/licenses/installed-packages.ts';
import type { InstalledPackage } from '../../src/licenses/installed-packages.ts';
import { externalPrograms, narrationComponents } from '../../src/licenses/notice-extras.ts';
import type { NoticeExtras } from '../../src/licenses/notice-extras.ts';
import { noticeRows, renderThirdPartyNotice } from '../../src/licenses/notice.ts';

const fixtureRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..', 'fixtures', 'licenses');

const tinyExtras: NoticeExtras = {
  externalPrograms: [{ name: 'tool', license: 'GPL-3.0-or-later', notes: 'External program.' }],
  narrationComponents: [{ name: 'voice', version: '1.0.0', license: 'Apache-2.0', notes: 'Installed on request.' }],
};

const expectedFixtureNotice = [
  '# Third-party notices',
  '',
  'This file is generated by `node scripts/licenses.ts --write` from the packages installed under `node_modules` and the `package-lock.json` of this repository; do not edit it by hand. The verbatim license texts of the production dependencies, and the NOTICE files of those that ship one, are under `docs/licenses/`.',
  '',
  '## Production dependencies',
  '',
  '| Package | Version | License | Repository |',
  '| --- | --- | --- | --- |',
  '| @scope/alpha | 1.0.0 | MIT | <https://github.com/scope/alpha> |',
  '| beta | 2.0.0 | (MIT OR Apache-2.0) | <https://github.com/example/beta> |',
  '| gamma | 1.5.0 | BSD-3-Clause | <https://github.com/example/gamma> |',
  '| legacy | 0.1.0 | ISC | <https://github.com/example/legacy> |',
  '',
  '## Development dependencies',
  '',
  '| Package | Version | License | Repository |',
  '| --- | --- | --- | --- |',
  '| copyleft | 4.0.0 | (MIT AND GPL-3.0-only) | <https://github.com/example/copyleft> |',
  '| gamma | 1.0.0 | MIT | <https://github.com/example/gamma> |',
  '| no-license | 3.0.0 | (missing) | (none) |',
  '',
  '## External programs (not bundled)',
  '',
  'Installed separately by the user and run as child processes; never copied into this repository or its outputs.',
  '',
  '| Program | License | Notes |',
  '| --- | --- | --- |',
  '| tool | GPL-3.0-or-later | External program. |',
  '',
  '## Optional narration component (installed separately on request)',
  '',
  'Installed into the data directory by `node scripts/cli.ts audio install` after the user confirms the sizes and licenses (ADR 0007); not part of this repository.',
  '',
  '| Component | Version | License | Notes |',
  '| --- | --- | --- | --- |',
  '| voice | 1.0.0 | Apache-2.0 | Installed on request. |',
  '',
].join('\n');

describe('renderThirdPartyNotice', () => {
  it('renders the fixture tree as the expected markdown, sorted by name with production and development apart', () => {
    const report = checkLicenses(readInstalledPackages(fixtureRoot));
    assert.equal(renderThirdPartyNotice(report.checks, tinyExtras), expectedFixtureNotice);
  });

  it('lists the real external programs and the narration component with their licenses', () => {
    const text = renderThirdPartyNotice([], { externalPrograms, narrationComponents });
    assert.match(text, /^\| ffmpeg \| LGPL-2\.1-or-later, or GPL-2\.0-or-later depending on the build \| /m);
    assert.match(text, /^\| Blender \| GPL-3\.0-or-later \| /m);
    assert.match(text, /^\| Microsoft Edge \/ Google Chrome \| Proprietary \| .*CDP/m);
    assert.match(text, /^\| kokoro-js \| 1\.2\.1 \| Apache-2\.0 \| /m);
    assert.match(text, /^\| @huggingface\/transformers \| 3\.8\.1 \| Apache-2\.0 \| /m);
    assert.match(text, /^\| onnxruntime-node \| 1\.21\.0 \| MIT \| .*DirectML\.dll/m);
    assert.match(text, /^\| phonemizer \| 1\.2\.1 \| .*https:\/\/github\.com\/xenova\/phonemizer\.js\/issues\/6/m);
    assert.match(text, /^\| sharp and @img\/sharp-win32-x64 \| 0\.34\.5 \| Apache-2\.0 AND LGPL-3\.0-or-later \| /m);
    assert.match(text, /^\| onnx-community\/Kokoro-82M-v1\.0-ONNX \(model weights\) \| v1\.0 \| Apache-2\.0 \| /m);
    assert.match(text, /## Production dependencies\n\nNone\.\n/);
  });

  it('escapes pipes in cells so the table stays intact', () => {
    const text = renderThirdPartyNotice([], { externalPrograms: [{ name: 'a|b', license: 'MIT', notes: 'x' }], narrationComponents: [] });
    assert.match(text, /^\| a\\\|b \| MIT \| x \|$/m);
  });
});

describe('noticeRows', () => {
  it('keeps one row per name and version and prefers the production copy', () => {
    const copy = (path: string, dev: boolean): InstalledPackage => ({ name: 'dup', version: '1.0.0', path, license: 'MIT', repository: undefined, dev });
    const report = checkLicenses([copy('node_modules/a/node_modules/dup', true), copy('node_modules/dup', false)]);
    assert.deepEqual(noticeRows(report.checks), [{ name: 'dup', version: '1.0.0', license: 'MIT', repository: undefined, dev: false }]);
  });
});
