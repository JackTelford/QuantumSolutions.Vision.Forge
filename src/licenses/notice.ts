/**
 * Renders THIRD-PARTY.md: a generated heading, one table of production
 * dependencies, one of development dependencies, then the external
 * programs and the optional narration component. Rows are sorted by name
 * and version and de-duplicated, so the same lock file gives the same text
 * on every machine.
 */
import type { LicenseCheck } from './check.ts';
import type { NoticeExtras } from './notice-extras.ts';
import { compareNameVersion, nameVersionKey } from './order.ts';

/** One row of a dependency table. */
export interface NoticeRow {
  readonly name: string;
  readonly version: string;
  readonly license: string;
  readonly repository: string | undefined;
  readonly dev: boolean;
}

/** Shown in the license column when a package declares none. */
export const missingLicenseText = '(missing)';

/** One row per name and version, sorted; a copy that is a production dependency wins over a dev-only copy. */
export function noticeRows(checks: readonly LicenseCheck[]): NoticeRow[] {
  const rows = new Map<string, NoticeRow>();
  for (const check of checks) {
    const key = nameVersionKey(check.pkg);
    const row: NoticeRow = { name: check.pkg.name, version: check.pkg.version, license: check.license ?? missingLicenseText, repository: check.pkg.repository, dev: check.pkg.dev };
    const existing = rows.get(key);
    if (existing === undefined || (existing.dev && !row.dev)) rows.set(key, row);
  }
  return [...rows.values()].sort(compareNameVersion);
}

function escapeCell(text: string): string {
  return text.replace(/\r?\n/g, ' ').replace(/\|/g, '\\|');
}

function markdownTable(headers: readonly string[], rows: readonly (readonly string[])[]): string[] {
  return [
    `| ${headers.join(' | ')} |`,
    `| ${headers.map(() => '---').join(' | ')} |`,
    ...rows.map((row) => `| ${row.map(escapeCell).join(' | ')} |`),
  ];
}

function dependencyTable(rows: readonly NoticeRow[]): string[] {
  if (rows.length === 0) return ['None.'];
  return markdownTable(['Package', 'Version', 'License', 'Repository'], rows.map((row) => [row.name, row.version, row.license, row.repository === undefined ? '(none)' : `<${row.repository}>`]));
}

/** Renders the whole notice as markdown with LF line endings and one trailing newline. */
export function renderThirdPartyNotice(checks: readonly LicenseCheck[], extras: NoticeExtras): string {
  const rows = noticeRows(checks);
  const lines = [
    '# Third-party notices',
    '',
    'This file is generated by `node scripts/licenses.ts --write` from the packages installed under `node_modules` and the `package-lock.json` of this repository; do not edit it by hand. The verbatim license texts of the production dependencies, and the NOTICE files of those that ship one, are under `docs/licenses/`.',
    '',
    '## Production dependencies',
    '',
    ...dependencyTable(rows.filter((row) => !row.dev)),
    '',
    '## Development dependencies',
    '',
    ...dependencyTable(rows.filter((row) => row.dev)),
    '',
    '## External programs (not bundled)',
    '',
    'Installed separately by the user and run as child processes; never copied into this repository or its outputs.',
    '',
    ...markdownTable(['Program', 'License', 'Notes'], extras.externalPrograms.map((program) => [program.name, program.license, program.notes])),
    '',
    '## Optional narration component (installed separately on request)',
    '',
    'Installed into the data directory by `node scripts/cli.ts audio install` after the user confirms the sizes and licenses (ADR 0007); not part of this repository.',
    '',
    ...markdownTable(['Component', 'Version', 'License', 'Notes'], extras.narrationComponents.map((component) => [component.name, component.version, component.license, component.notes])),
  ];
  return `${lines.join('\n')}\n`;
}
